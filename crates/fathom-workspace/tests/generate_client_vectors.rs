fn client_vectors_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../client/src/document/vectors")
}

/// One fixture: the bytes and the plain-words sidecar describing them.
struct Vector {
    name: &'static str,
    bytes: Vec<u8>,
    sidecar: String,
}

fn sidecar(
    name: &str,
    description: &str,
    node_count: usize,
    edge_count: usize,
    kinds: &[&str],
    edges: &[&str],
) -> String {
    let kinds_json = kinds
        .iter()
        .map(|k| format!("\"{k}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let edges_json = edges
        .iter()
        .map(|e| format!("\"{e}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "{{\n  \"name\": \"{name}\",\n  \"description\": \"{description}\",\n  \"node_count\": \
         {node_count},\n  \"edge_count\": {edge_count},\n  \"kinds\": [{kinds_json}],\n  \
         \"edges\": [{edges_json}]\n}}\n"
    )
}

/// The one-shot generator (ADR-0049 #3). `--ignored`: this writes files
/// under the client tree, which `cargo test` must not do on every run.
/// `--nocapture` to see where each vector landed.
#[test]
#[ignore = "writes client/src/document/vectors/ -- run explicitly, see this file's module doc"]
fn write_client_vectors() {
    let vectors = vec![
        Vector {
            name: "empty",
            bytes: write_plain(&empty_graph()).expect("writes"),
            sidecar: sidecar(
                "empty",
                "A graph with nothing in it: no nodes, no edges, no batches, no history, no \
                 provenance. This is the whole document, not a placeholder for one.",
                0,
                0,
                &[],
                &[],
            ),
        },
        Vector {
            name: "one-rack",
            bytes: write_plain(&one_rack_graph()).expect("writes"),
            sidecar: sidecar(
                "one-rack",
                "One Premises node and one Rack node, joined by a HasRack edge. The Rack \
                 carries label \\\"R1\\\", height_u 42 and unit_numbering \\\"ascending\\\". \
                 Every value is a sample: a real design could give the rack any label, any \
                 height_u in Rack's declared range 1..100, and either unit_numbering.",
                2,
                1,
                &["Premises", "Rack"],
                &["HasRack"],
            ),
        },
        Vector {
            name: "two-chassis",
            bytes: write_plain(&two_chassis_graph()).expect("writes"),
            sidecar: sidecar(
                "two-chassis",
                "Builds on one-rack.plain: the same Premises and Rack (label \\\"R1\\\", \
                 height_u 42, ascending), plus two Device nodes, each with one Chassis \
                 (HasChassis). Each chassis is MountedIn the rack at a different position_u \
                 (10 and 20) with face set (front and rear -- both sampled, not a rule: \
                 MountedIn.face is optional and either value is legal). The first chassis \
                 owns 2 PhysicalPort nodes, the second owns 3, each attached via HasPort and \
                 carrying a label (\\\"1\\\", \\\"2\\\", ...), a position and a connector \
                 (rj45, sfp_plus, qsfp28 -- sampled from PhysicalPort.connector's closed \
                 vocabulary, not the only legal values). PhysicalPort.position is set on \
                 every port, but 19 section 3.3's PortPosition shape has no modelled fields yet \
                 (fathom-ir's own value::PortPosition stub), so on the wire it is the empty \
                 object {}; setting it records only that a position is known, not what it is. \
                 Every label, position_u, face and connector value here is a sample, never a \
                 fixed convention.",
                11,
                10,
                &["Premises", "Rack", "Device", "Chassis", "PhysicalPort"],
                &["HasRack", "HasChassis", "MountedIn", "HasPort"],
            ),
        },
    ];

    let dir = client_vectors_dir();
    fs::create_dir_all(&dir).unwrap_or_else(|e| panic!("could not create {}: {e}", dir.display()));

    for vector in vectors {
        let plain_path = dir.join(format!("{}.plain", vector.name));
        let json_path = dir.join(format!("{}.json", vector.name));
        fs::write(&plain_path, &vector.bytes)
            .unwrap_or_else(|e| panic!("could not write {}: {e}", plain_path.display()));
        fs::write(&json_path, vector.sidecar.as_bytes())
            .unwrap_or_else(|e| panic!("could not write {}: {e}", json_path.display()));
        println!(
            "wrote {} ({} bytes)",
            plain_path.display(),
            vector.bytes.len()
        );
        println!("wrote {}", json_path.display());
    }
}
