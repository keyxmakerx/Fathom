//! Golden vectors for every authority construction — **two independent
//! assemblies agreeing**, plus Wycheproof.
//!
//! `docs/PHASE-2-ADMIN-AND-AUDIT-DESIGN.md` §3.2, §3.3, §3.4 and §6.1.
//!
//! # Why this file exists, and what it is not
//!
//! The hex below was produced by
//! `crates/fathom-server/tests/vectors/gen_authority_vectors.py`, which lays
//! out every message from the text of §3 in plain Python, with its own `lp`,
//! `u32_le`, `u64_le`, SHA-256, HMAC-SHA-256, HKDF-Expand **and its own P-256
//! arithmetic**. **It does not call the Rust code, and this test does not call
//! the script.** The literals are literals. If the two agree, two people
//! reading the same specification laid the bytes out the same way; if either
//! is edited — a length prefix dropped, a field reordered, a label "tidied" —
//! they stop agreeing, and that is the whole of the control.
//!
//! `chain_vectors.rs` makes the same argument for the chain construction and
//! records what happens without it: the seal correction of 2026-09-12 was
//! pinned by nothing at all, and removing it left every test in this workspace
//! green.
//!
//! # What a failure here means
//!
//! Not "a test is broken". Either a signed construction changed — in which
//! case every signature ever made is invalidated and the change needs the
//! argument §3's own correction had to make — or it changed by accident, in
//! which case it is a silent break of every stored grant. Regenerating the
//! vectors to make this pass is the one repair that is never right.
//!
//! # The Wycheproof half
//!
//! `ecdsa_secp256r1_sha256_p1363_test.json` and
//! `ecdsa_secp256r1_sha256_test.json` from `C2SP/wycheproof`
//! (raw.githubusercontent.com, reachable and fetched 2026-09-12). The cases are
//! curated by the generator script, and **the expected outcome is this
//! product's, not Wycheproof's**: a Wycheproof-valid signature whose `s` is
//! high is refused here, because §3's correction admits exactly one encoding
//! per act. The script classifies `s` itself and derives the `(r, −s)` twin of
//! a valid case, because Wycheproof's own P1363 group carries no high-`s`
//! valid signature.

