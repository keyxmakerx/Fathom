#[test]
fn signing_is_deterministic_and_the_signature_is_the_pinned_one() {
    // RFC 6979: `ecdsa 0.17.0`'s `Signer` derives the ephemeral scalar from
    // the key and the message, so this is a fixed value — and the Python
    // script VERIFIES it with its own P-256 arithmetic over its own
    // `grant_bytes`, which is the independent half.
    let key = SoftwareKey::from_bytes(&private_scalar()).expect("a valid scalar");
    let signature = key.sign(&authority::grant_bytes(&facts()));
    assert_eq!(hex(&signature), SIGNATURE);
    assert_eq!(
        authority::verify_es256(
            &key.public_key(),
            &authority::grant_bytes(&facts()),
            &signature
        ),
        Ok(())
    );
}

#[test]
fn wycheproof_cases_get_this_products_answer_and_not_wycheproofs() {
    assert!(
        !WYCHEPROOF.is_empty(),
        "the Wycheproof table is empty, which would make this test pass by \
         checking nothing. Re-run tests/vectors/gen_authority_vectors.py where \
         raw.githubusercontent.com is reachable and paste its table back."
    );
    for (public, message, signature, expected) in WYCHEPROOF {
        let outcome = authority::verify_es256(&unhex(public), &unhex(message), &unhex(signature));
        let got = match outcome {
            Ok(()) => "Ok".to_string(),
            Err(SignatureRefused::HighS) => "HighS".to_string(),
            Err(SignatureRefused::WrongLength { .. }) => "WrongLength".to_string(),
            Err(SignatureRefused::Malformed) => "Malformed".to_string(),
            Err(SignatureRefused::DoesNotVerify) => "DoesNotVerify".to_string(),
            Err(SignatureRefused::PublicKeyMalformed) => "PublicKeyMalformed".to_string(),
        };
        assert_eq!(&got, expected, "signature {signature}");
    }
}
