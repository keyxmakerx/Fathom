fn chain_master() -> Key32 {
    let mut bytes = [0u8; 32];
    for (i, b) in bytes.iter_mut().enumerate() {
        *b = i as u8;
    }
    Key32::from_bytes(bytes)
}

fn private_scalar() -> [u8; 32] {
    [0x07; 32]
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex(text: &str) -> Vec<u8> {
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&text[i..i + 2], 16).expect("hex"))
        .collect()
}

fn facts() -> GrantFacts<'static> {
    GrantFacts {
        organisation: ORGANISATION,
        root_pubkey_fpr: &ROOT_PUBKEY_FPR,
        scope: SCOPE,
        subject: SUBJECT,
        subject_key_fpr: &SUBJECT_KEY_FPR,
        capability: Capability::Steward,
        granter: Some(GRANTER),
        granter_key_fpr: &GRANTER_KEY_FPR,
        effective_from_unix: EFFECTIVE_FROM,
        expires_at_unix: EXPIRES_AT,
        auth_epoch: AUTH_EPOCH,
    }
}

