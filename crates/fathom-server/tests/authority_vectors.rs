#[test]
fn second_bytes_bind_the_grant_and_the_granters_key_and_nothing_else() {
    let grant = authority::grant_bytes(&facts());
    assert_eq!(
        hex(&authority::second_bytes(&grant, &GRANTER_KEY_FPR)),
        SECOND_BYTES
    );
}

#[test]
fn revoke_suspend_and_unsuspend_bytes_are_three_different_messages() {
    let grant = authority::grant_bytes(&facts());
    assert_eq!(
        hex(&authority::revoke_bytes(
            ORGANISATION,
            GRANT_ID,
            &grant,
            AT_UNIX
        )),
        REVOKE_BYTES
    );
    assert_eq!(
        hex(&authority::suspend_bytes(
            ORGANISATION,
            GRANT_ID,
            &grant,
            AT_UNIX
        )),
        SUSPEND_BYTES
    );
    assert_eq!(
        hex(&authority::unsuspend_bytes(
            ORGANISATION,
            GRANT_ID,
            &grant,
            AT_UNIX
        )),
        UNSUSPEND_BYTES
    );
}

