#[test]
fn the_row_key_is_a_third_subkey_of_the_organisation_chain_key() {
    let chain_key = chain::chain_key(
        &chain_master(),
        ChainRef::Org {
            organisation: ORGANISATION,
        },
        CHAIN_KEY_EPOCH,
    );
    assert_eq!(hex(chain_key.expose()), ORG_CHAIN_KEY);
    assert_eq!(hex(authority::row_key(&chain_key).expose()), K_ROW);
    assert_eq!(
        hex(chain::Subkeys::derive(&chain_key).seal.expose()),
        K_SEAL
    );
}

#[test]
fn the_row_seal_is_the_seal_the_document_describes() {
    let chain_key = chain::chain_key(
        &chain_master(),
        ChainRef::Org {
            organisation: ORGANISATION,
        },
        CHAIN_KEY_EPOCH,
    );
    let seal = authority::row_seal(
        &authority::row_key(&chain_key),
        &RowFacts {
            table: "scope_grants",
            row_id: GRANT_ID,
            chain_seq: ROW_CHAIN_SEQ,
            row_version: ROW_VERSION,
            row_state: ROW_STATE,
        },
    );
    assert_eq!(hex(&seal), ROW_SEAL);
}

#[test]
fn the_live_digest_and_the_head_seal_are_the_ones_the_document_describes() {
    let chain_key = chain::chain_key(
        &chain_master(),
        ChainRef::Org {
            organisation: ORGANISATION,
        },
        CHAIN_KEY_EPOCH,
    );
    let row_key = authority::row_key(&chain_key);
    // Handed over deliberately UNSORTED, because §3.4 sorts and the code must
    // not depend on its caller having done so.
    let live = vec![
        ("01JQZ0000000000000000000GG".to_string(), [0x61u8; 32]),
        ("01JQZ0000000000000000000EE".to_string(), [0x62u8; 32]),
    ];
    let digest = authority::live_digest(&row_key, ORGANISATION, AUTH_EPOCH, &live);
    assert_eq!(hex(&digest), LIVE_DIGEST);

    let seal = authority::head_seal(
        &chain::Subkeys::derive(&chain_key).seal,
        ORGANISATION,
        AUTH_EPOCH,
        HEAD_CHAIN_SEQ,
        &digest,
    );
    assert_eq!(hex(&seal), HEAD_SEAL);
}

