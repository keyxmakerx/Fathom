#[test]
fn the_request_message_matches_the_document() {
    let message = sessions::request_bytes(
        SESSION_ID,
        METHOD,
        PATH,
        &sessions::body_digest(BODY),
        &REQUEST_NONCE,
        UNIX_MS,
        REQUEST_COUNTER,
    );
    assert_eq!(
        hex(&message),
        hex(&unhex(REQUEST_BYTES)),
        "the per-request message is the one thing every protected route in this server rests on, \
         and the nonce inside it is this build's own addition to §4.2's layout"
    );
}

#[test]
fn the_signature_over_the_request_message_is_the_one_the_generator_verified() {
    // The generator cannot PRODUCE this signature -- RFC 6979's nonce
    // derivation is the signer's -- so it verifies it instead, with its own
    // P-256 arithmetic, over the message it assembled itself. That is the
    // stronger check of the two: a wrong `request_bytes` on either side makes
    // the verification fail.
    let signature = session_key().sign(&unhex(REQUEST_BYTES));
    assert_eq!(hex(&signature), SIGNATURE);
    assert_eq!(
        authority::verify_es256(
            &session_key().public_key(),
            &unhex(REQUEST_BYTES),
            &unhex(SIGNATURE)
        ),
        Ok(())
    );
}

