#[test]
fn the_session_row_mac_matches_the_document() {
    let key = Key32::from_bytes(
        unhex(K_ROW_SITE)
            .try_into()
            .expect("the row key is 32 bytes"),
    );
    let challenge =
        sessions::session_challenge(&session_key().public_key(), &SERVER_NONCE, DEPLOYMENT);
    let digest = sessions::evidence_digest(&challenge, &EVIDENCE_SIG);
    let pubkey = session_key().public_key();
    let token_hash = sessions::token_hash(&TOKEN);
    let mac = sessions::session_row_mac(
        &key,
        &SessionFacts {
            id: SESSION_ID,
            principal_id: PRINCIPAL_ID,
            principal_kind: PrincipalKind::Steward,
            token_hash: &token_hash,
            session_pubkey: &pubkey,
            bound_nonce: &SERVER_NONCE,
            evidence_key_id: Some(EVIDENCE_KEY_ID),
            evidence_sig: Some(&EVIDENCE_SIG),
            assertion_digest: Some(&digest),
            assurance: Assurance::A1,
            chain_seq: CHAIN_SEQ,
            row_version: ROW_VERSION,
            issued_at_unix: ISSUED_AT,
            expires_at_unix: EXPIRES_AT,
        },
    );
    assert_eq!(
        hex(&mac),
        ROW_MAC,
        "§4.3's second fence: a tier-2 attacker cannot mint a session row, because this key is \
         not in PostgreSQL. The canonical row state it is taken over is assembled twice, once \
         here and once in Python"
    );
}

#[test]
fn every_field_of_the_row_state_is_inside_the_mac() {
    // The vector proves one value. This proves the fields are load-bearing:
    // change any one of them and the MAC moves. A construction that dropped a
    // field would still match the vector if the vector were the only test.
    let key = Key32::from_bytes([9u8; 32]);
    let pubkey = session_key().public_key();
    let token_hash = sessions::token_hash(&TOKEN);
    let digest = [7u8; 32];
    let facts = || SessionFacts {
        id: SESSION_ID,
        principal_id: PRINCIPAL_ID,
        principal_kind: PrincipalKind::Steward,
        token_hash: &token_hash,
        session_pubkey: &pubkey,
        bound_nonce: &SERVER_NONCE,
        evidence_key_id: Some(EVIDENCE_KEY_ID),
        evidence_sig: Some(&EVIDENCE_SIG),
        assertion_digest: Some(&digest),
        assurance: Assurance::A1,
        chain_seq: CHAIN_SEQ,
        row_version: ROW_VERSION,
        issued_at_unix: ISSUED_AT,
        expires_at_unix: EXPIRES_AT,
    };
    let base = sessions::session_row_mac(&key, &facts());

    let other_token = [0x99u8; 32];
    let other_nonce = [0x98u8; 32];
    let other_digest = [0x97u8; 32];
    let variants: Vec<SessionFacts<'_>> = vec![
        SessionFacts {
            id: "01JQZ0000000000000000000ST",
            ..facts()
        },
        SessionFacts {
            principal_id: "01JQZ0000000000000000000AB",
            ..facts()
        },
        SessionFacts {
            principal_kind: PrincipalKind::Operator,
            ..facts()
        },
        SessionFacts {
            token_hash: &other_token,
            ..facts()
        },
        SessionFacts {
            bound_nonce: &other_nonce,
            ..facts()
        },
        SessionFacts {
            evidence_key_id: None,
            ..facts()
        },
        SessionFacts {
            assertion_digest: Some(&other_digest),
            ..facts()
        },
        SessionFacts {
            assurance: Assurance::A0,
            ..facts()
        },
        SessionFacts {
            chain_seq: CHAIN_SEQ + 1,
            ..facts()
        },
        SessionFacts {
            row_version: ROW_VERSION + 1,
            ..facts()
        },
        SessionFacts {
            issued_at_unix: ISSUED_AT + 1,
            ..facts()
        },
        SessionFacts {
            expires_at_unix: EXPIRES_AT + 1,
            ..facts()
        },
    ];
    for (n, variant) in variants.iter().enumerate() {
        assert_ne!(
            base,
            sessions::session_row_mac(&key, variant),
            "field {n} is not covered by the session row MAC"
        );
    }
}

#[test]
fn a_session_row_mac_is_not_an_authority_row_seal() {
    // `row_seal` length-prefixes the table name, so a session row lifted into
    // an authority table -- or the reverse -- does not verify where it lands.
    let key = Key32::from_bytes([5u8; 32]);
    let pubkey = session_key().public_key();
    let token_hash = sessions::token_hash(&TOKEN);
    let state = sessions::session_row_mac(
        &key,
        &SessionFacts {
            id: SESSION_ID,
            principal_id: PRINCIPAL_ID,
            principal_kind: PrincipalKind::Steward,
            token_hash: &token_hash,
            session_pubkey: &pubkey,
            bound_nonce: &SERVER_NONCE,
            evidence_key_id: None,
            evidence_sig: None,
            assertion_digest: None,
            assurance: Assurance::A0,
            chain_seq: CHAIN_SEQ,
            row_version: ROW_VERSION,
            issued_at_unix: ISSUED_AT,
            expires_at_unix: EXPIRES_AT,
        },
    );
    let elsewhere = authority::row_seal(
        &key,
        &authority::RowFacts {
            table: "scope_grants",
            row_id: SESSION_ID,
            chain_seq: CHAIN_SEQ,
            row_version: ROW_VERSION,
            row_state: b"{}\n",
        },
    );
    assert_ne!(state, elsewhere);
}

#[test]
fn the_label_list_is_the_one_the_generator_used() {
    // `PHASE-2-STORAGE-DESIGN.md` §12.2's table owns these names and wins over
    // the code. This asserts the two files at least agree on the set.
    let generator = include_str!("vectors/gen_session_vectors.py");
    for (label, _) in sessions::LABELS {
        assert!(
            generator.contains(label),
            "{label} is in sessions::LABELS and the generator does not know it, so one of the \
             two assemblies is not assembling it"
        );
    }
}
