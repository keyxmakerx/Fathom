//! Golden vectors for the session layer: the hex `gen_session_vectors.py`
//! printed, recomputed here through `fathom_server::sessions`.
//!
//! **THE POINT IS TWO INDEPENDENT ASSEMBLIES AGREEING.**
//!
//! `tests/vectors/gen_session_vectors.py` builds every message below in plain
//! Python, from the text of `docs/PHASE-2-ADMIN-AND-AUDIT-DESIGN.md` §4.2 and
//! §4.3 — its own length prefixes, its own SHA-256, HMAC and HKDF, its own
//! canonical-JSON emitter and its own P-256 arithmetic. The constants here are
//! that script's output, pasted. Nothing in this file reads the script and
//! nothing in the script reads this file: if a length prefix is dropped, a
//! field reordered, a label tidied or the nonce quietly taken back out of
//! `request_bytes`, the two stop agreeing.
//!
//! A test that called the Rust code to produce its own expected value would
//! pass for any construction whatsoever, which is why none of these does.
//!
//! No database, no keys on disk, no network: every value is a pure function of
//! the constants at the top of the generator.

