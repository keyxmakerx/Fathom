//! Golden vectors for every chain construction — **two independent assemblies
//! agreeing.**
//!
//! `docs/PHASE-2-STORAGE-DESIGN.md` §11.2 and §12.2, and `0009`'s two extra
//! labels.
//!
//! # Why this file exists, and what it is not
//!
//! The hex below was produced by
//! `crates/fathom-server/tests/vectors/gen_chain_vectors.py`, which lays out
//! every message from the text of §11.2 and §12.2 in plain Python, with its own
//! `lp`, `u32_le`, `u64_le`, HMAC-SHA-256 and HKDF-Expand. **It does not call
//! the Rust code, and this test does not call the script.** The literals are
//! literals. If the two agree, two people reading the same specification laid
//! the bytes out the same way; if either is edited — a length prefix dropped, a
//! field reordered, a label "tidied" — they stop agreeing, and that is the
//! whole of the control.
//!
//! **A test that derived its expected value from `fathom_server::chain` would
//! pass for any construction whatsoever**, including one with
//! `LP(metadata_binding)` deleted from the seal. That is not hypothetical: the
//! seal correction of 2026-09-12 was pinned by nothing at all, and removing it
//! left every test in this workspace green.
//!
//! # What a failure here means
//!
//! Not "a test is broken". Either the construction changed, in which case every
//! seal ever written is invalidated and the change needs the argument §11.2's
//! own correction had to make, or the change was accidental, in which case it
//! is a silent break of every stored history. Regenerating the vectors to make
//! this pass is the one repair that is never right.

