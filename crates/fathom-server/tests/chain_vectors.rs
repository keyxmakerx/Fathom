#[test]
fn the_three_chain_key_derivations_and_the_site_metadata_key() {
    // §12.2's table, three of its rows plus `0009`'s. Each is length-prefixed
    // and domain-separated, which is what stops a run of entries lifted from
    // one chain verifying at another -- and what stops tenant `ab` + design
    // `c` deriving the same key as tenant `a` + design `bc`.
    let master = chain_master();
    assert_eq!(
        hex(chain::chain_key(&master, DESIGN_CHAIN, CHAIN_KEY_EPOCH).expose()),
        DESIGN_CHAIN_KEY,
        "the per-design chain key -- §12.2. This one may NEVER change: every seal already \
         written verifies under it."
    );
    assert_eq!(
        hex(chain::chain_key(
            &master,
            ChainRef::Site {
                deployment: DEPLOYMENT
            },
            CHAIN_KEY_EPOCH
        )
        .expose()),
        SITE_CHAIN_KEY,
    );
    assert_eq!(
        hex(chain::chain_key(
            &master,
            ChainRef::Org {
                organisation: TENANT
            },
            CHAIN_KEY_EPOCH
        )
        .expose()),
        ORG_CHAIN_KEY,
    );
    assert_eq!(
        hex(chain::site_metadata_key(&master, DEPLOYMENT, CHAIN_KEY_EPOCH).expose()),
        SITE_METADATA_KEY,
    );

    // And the three are different keys, which is the property the labels buy.
    assert_ne!(DESIGN_CHAIN_KEY, SITE_CHAIN_KEY);
    assert_ne!(SITE_CHAIN_KEY, ORG_CHAIN_KEY);
    assert_ne!(SITE_CHAIN_KEY, SITE_METADATA_KEY);
}

#[test]
fn the_two_subkeys() {
    // §12.2 renamed these labels so that the HKDF `info` and the in-MAC domain
    // tag are not the same literal. Pinned here because the failure mode of
    // "tidying" one of them is silent.
    let subkeys = Subkeys::derive(&chain::chain_key(
        &chain_master(),
        DESIGN_CHAIN,
        CHAIN_KEY_EPOCH,
    ));
    assert_eq!(hex(subkeys.seal.expose()), K_SEAL);
    assert_eq!(hex(subkeys.content.expose()), K_CONTENT);
}

#[test]
fn the_bindings_and_the_content_hash() {
    let subkeys = Subkeys::derive(&chain::chain_key(
        &chain_master(),
        DESIGN_CHAIN,
        CHAIN_KEY_EPOCH,
    ));

    // The data key's non-secret id, which is what enters `storage_binding` --
    // not the key.
    assert_eq!(hex(data_key().id().as_bytes()), DATA_KEY_ID);

    let plaintext = chain::plaintext_binding(
        &subkeys.content,
        &PlaintextFacts {
            tenant: TENANT,
            design: DESIGN,
            design_version: DESIGN_VERSION,
            payload_schema_version: PAYLOAD_SCHEMA_VERSION,
            payload: PAYLOAD,
        },
    );
    assert_eq!(hex(&plaintext), PLAINTEXT_BINDING);

    let storage = chain::storage_binding(
        &subkeys.content,
        &StorageFacts {
            key_id: data_key().id(),
            key_epoch: KEY_EPOCH,
            wrap_version: WRAP_VERSION,
            aead_alg_id: AEAD_ALG_ID,
            nonce: &nonce(),
            ciphertext: CIPHERTEXT,
        },
    );
    assert_eq!(hex(&storage), STORAGE_BINDING);

    let content_hash = chain::content_hash(&subkeys.content, &plaintext, &storage);
    assert_eq!(hex(&content_hash), CONTENT_HASH);

    assert_eq!(
        hex(&chain::metadata_binding(
            &subkeys.content,
            METADATA_CANONICAL
        )),
        METADATA_BINDING,
    );
    assert_eq!(
        hex(&chain::absent_content_binding(&subkeys.content)),
        ABSENT_CONTENT_BINDING,
    );
}

#[test]
fn the_seal_covers_the_metadata_as_stored_and_the_binding_of_its_plaintext() {
    // **The construction that was pinned by nothing.** `metadata_stored` and
    // the value `metadata_binding` covers are DIFFERENT bytes in this vector,
    // deliberately: a vector that used one value for both would agree with a
    // construction that had confused them, and one that omitted either would
    // agree with a seal that had dropped it.
    let subkeys = Subkeys::derive(&chain::chain_key(
        &chain_master(),
        DESIGN_CHAIN,
        CHAIN_KEY_EPOCH,
    ));
    let metadata_binding = chain::metadata_binding(&subkeys.content, METADATA_CANONICAL);
    let content_hash = {
        let mut bytes = [0u8; 32];
        for (i, b) in bytes.iter_mut().enumerate() {
            // The vector's `content_hash`, parsed back from its own hex so
            // this test does not depend on the binding test above passing.
            *b = u8::from_str_radix(&CONTENT_HASH[i * 2..i * 2 + 2], 16).unwrap();
        }
        bytes
    };

    let facts = SealFacts {
        chain_key_epoch: CHAIN_KEY_EPOCH,
        seq: SEQ,
        chain: DESIGN_CHAIN,
        prev_seal: &prev_seal(),
        content_hash: &content_hash,
        entry_type: EntryType::Update,
        metadata_stored: METADATA_STORED,
        metadata_binding: &metadata_binding,
    };
    assert_eq!(
        hex(&chain::seal(&subkeys.seal, &facts)),
        SEAL,
        "the seal input is §11.2's as corrected on 2026-09-12: \
         LP(tag) || u32(epoch) || u64(seq) || LP(id1) || LP(id2) || LP(prev_seal) || \
         LP(content_hash) || LP(entry_type) || LP(metadata_stored) || LP(metadata_binding)"
    );

    // And the verifier's constant-time path agrees with the value.
    let mut tag = [0u8; 32];
    for (i, b) in tag.iter_mut().enumerate() {
        *b = u8::from_str_radix(&SEAL[i * 2..i * 2 + 2], 16).unwrap();
    }
    assert!(chain::seal_verifies(&subkeys.seal, &facts, &tag));
}

#[test]
fn genesis_at_all_three_levels() {
    // §11.2's genesis, with the two deviations `chain::genesis` records: the
    // outer `LP` is how the value enters the MAC rather than part of it, and
    // the inner concatenation is length-prefixed.
    assert_eq!(hex(&chain::genesis(DESIGN_CHAIN)), GENESIS_DESIGN);
    assert_eq!(
        hex(&chain::genesis(ChainRef::Site {
            deployment: DEPLOYMENT
        })),
        GENESIS_SITE,
    );
    assert_eq!(
        hex(&chain::genesis(ChainRef::Org {
            organisation: TENANT
        })),
        GENESIS_ORG,
    );
}

#[test]
fn the_metadata_associated_data() {
    // `0009`'s label, and the reason a metadata blob cannot be moved to
    // another `seq`: the associated data names the row. The whole byte string
    // is pinned, not a digest of it, because it is short and because its shape
    // is the thing that matters.
    assert_eq!(
        hex(&chain::metadata_aad(
            ChainRef::Org {
                organisation: TENANT
            },
            SEQ,
            METADATA_KEY_EPOCH
        )),
        METADATA_AAD_ORG,
        "on an organisation entry the epoch is `metadata_key_epoch`, which names a row in \
         org_content_keys"
    );
    assert_eq!(
        hex(&chain::metadata_aad(
            ChainRef::Site {
                deployment: DEPLOYMENT
            },
            SEQ,
            CHAIN_KEY_EPOCH
        )),
        METADATA_AAD_SITE,
        "on a site entry it is `chain_key_epoch`, which is already on the row"
    );
}
